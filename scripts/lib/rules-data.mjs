// Shared by sync-data, validate-data, and gen-types: where the rules snapshot
// lives, how a rules folder is read, how it is validated, and how it is
// versioned. The workspace's domains/dnd-rules/data/ is the source of truth;
// data/rules/ in this repo is the copy a build ships with: its schemas/ and
// its public tier, srd/. The private tier, books/, never enters this repo
// (the spec §2.1): nothing here reads it.

import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import Ajv2020 from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'
import { checkIntegrity } from './integrity.mjs'

export const REPO_ROOT = path.resolve(import.meta.dirname, '../..')
export const SNAPSHOT_DIR = path.join(REPO_ROOT, 'data', 'rules')
export const MANIFEST_NAME = 'manifest.json'
// The folders a rules folder holds: the public tier's data, and the schemas
// it is checked against.
export const DATA_SUB = 'srd'
export const SCHEMA_SUB = 'schemas'

const MAX_ERRORS_PER_FILE = 15

// Every *.json in `dir/srd` and `dir/schemas`, parsed, sorted by name.
// README.md, the domain's own scripts, and the manifest are not rules data
// and are skipped.
export function readRulesFolder(dir) {
  const read = (sub) => {
    const folder = path.join(dir, sub)
    return fs
      .readdirSync(folder)
      .filter((name) => name.endsWith('.json') && name !== MANIFEST_NAME)
      .sort()
      .map((name) => {
        const text = fs.readFileSync(path.join(folder, name), 'utf8')
        try {
          return { name, text, json: JSON.parse(text) }
        } catch (err) {
          throw new Error(`${path.join(sub, name)} is not valid JSON: ${err.message}`, { cause: err })
        }
      })
  }
  return { data: read(DATA_SUB), schemas: read(SCHEMA_SUB) }
}

// Schema validation, then the cross-file integrity check. Returns problems
// rather than throwing, so the caller can print all of them at once.
// allowUnionTypes: the domain's schemas write a field that may hold either
// of two types as `type: [a, b]`, which Ajv's strict mode otherwise refuses.
export function validateRules({ data, schemas }) {
  const errors = []
  const ajv = new Ajv2020({ allErrors: true, allowUnionTypes: true })
  addFormats(ajv)
  for (const schema of schemas) ajv.addSchema(schema.json, schema.name)

  for (const file of data) {
    const schemaName = file.name.replace(/\.json$/, '.schema.json')
    const validate = ajv.getSchema(schemaName)
    if (!validate) {
      errors.push(`${file.name}: no schema at schemas/${schemaName} (schemas are written before data)`)
      continue
    }
    if (!validate(file.json)) {
      const found = validate.errors
      for (const e of found.slice(0, MAX_ERRORS_PER_FILE)) {
        errors.push(`${file.name}: ${e.instancePath || '(root)'} ${e.message}`)
      }
      if (found.length > MAX_ERRORS_PER_FILE) {
        errors.push(`${file.name}: …and ${found.length - MAX_ERRORS_PER_FILE} more schema errors`)
      }
    }
  }

  const integrity = checkIntegrity(Object.fromEntries(data.map((f) => [f.name, f.json])))
  return {
    errors: [...errors, ...integrity.errors],
    notes: integrity.notes,
    refsChecked: integrity.checked,
  }
}

// One version for the whole rules set, because a save stores a single
// gameDataVersion while the per-file meta.dataVersion values differ. A content
// hash changes whenever any file does, with nobody remembering to bump it.
// Hashed over re-serialized JSON, not raw bytes, so a CRLF checkout on Windows
// and an LF checkout on the build server get the same version.
export function rulesVersion({ data, schemas }) {
  const hash = createHash('sha256')
  for (const [folder, files] of [[DATA_SUB, data], [SCHEMA_SUB, schemas]]) {
    for (const f of files) hash.update(`${folder}/${f.name}\n${JSON.stringify(f.json)}\n`)
  }
  return hash.digest('hex').slice(0, 12)
}

// The manifest the app reads its gameDataVersion from. `syncedAt` only moves
// when the rules do, so re-running an unchanged sync leaves git clean. It
// carries the SRD's attribution statement too, which every srd file holds in
// meta, so Settings can show it without loading the rules.
export function buildManifest(rules, previous) {
  const version = rulesVersion(rules)
  return {
    about:
      "Generated by npm run sync-data; do not edit. rulesVersion is a content hash of every srd/ data file and schema, and is what a saved character records as its gameDataVersion. files carries each file's own meta.dataVersion for migrations. attribution is the SRD's licence statement, from the files' meta.",
    rulesVersion: version,
    syncedAt: previous?.rulesVersion === version ? previous.syncedAt : new Date().toISOString(),
    attribution: rules.data.find((f) => f.json.meta?.attribution)?.json.meta.attribution,
    files: Object.fromEntries(
      rules.data.map((f) => [f.name, { dataVersion: f.json.meta?.dataVersion, complete: f.json.meta?.complete, tier: f.json.meta?.tier }]),
    ),
    schemas: rules.schemas.map((s) => s.name),
  }
}

// What data/rules/ holds, by name, sorted: files and folders alike, so a test
// can hold it to the manifest, schemas/ and srd/, and never books/.
export function snapshotEntries() {
  return fs.readdirSync(SNAPSHOT_DIR).sort()
}

export function readManifest() {
  const file = path.join(SNAPSHOT_DIR, MANIFEST_NAME)
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : undefined
}

export function report({ errors, notes = [], refsChecked }) {
  for (const n of notes) console.log(`  reported ${n}`)
  for (const e of errors) console.error(`  error    ${e}`)
  if (refsChecked !== undefined) console.log(`  ${refsChecked} cross-file references checked`)
}
